// The whole word as one bitmap, letters set `gap` pixels apart.
export function setWord(set, word = "AKIBWA", gap = 2) {
  const glyphs = [...word].map((ch) => set[ch]);
  const height = Math.max(...glyphs.map((g) => g.length));
  const rows = Array.from({ length: height }, () => "");
  const starts = [];
  glyphs.forEach((g, n) => {
    starts.push(rows[0].length);
    const w = g[0].length;
    for (let r = 0; r < height; r += 1) rows[r] += (g[r] ?? ".".repeat(w)) + (n < glyphs.length - 1 ? ".".repeat(gap) : "");
  });
  return { rows, width: rows[0].length, height, starts };
}

